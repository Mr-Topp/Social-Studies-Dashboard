<p><b>Confederal: Many Different Chairs.</b> The confederal form of government is an association of independent states. The central government gets its authority from the people of the independent states. Power rests in each individual state, whose representatives meet to address the needs of the group. The U.S. tried a confederal system before the Constitution. It didn’t work because the states did not give the central government enough power to do its job on behalf of the states. (To do things like pay soldiers to fight the Revolutionary War, for example!) <i>A confederation of states is like a bunch of different chairs grouped together. They hold power independently but work collectively.</i></p>
